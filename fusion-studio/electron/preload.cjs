const {contextBridge,ipcRenderer}=require('electron');
contextBridge.exposeInMainWorld('fusion',{
  info:()=>ipcRenderer.invoke('info'),
  modelList:()=>ipcRenderer.invoke('models-list'),
  modelSave:profile=>ipcRenderer.invoke('models-save',profile),
  modelDelete:id=>ipcRenderer.invoke('models-delete',id),
  modelTest:(id,requestId)=>ipcRenderer.invoke('models-test',id,requestId),
  modelChat:request=>ipcRenderer.invoke('models-chat',request),
  modelCancel:id=>ipcRenderer.invoke('models-cancel',id),
  mcpStatus:()=>ipcRenderer.invoke('mcp-status'),
  mcpConfigure:settings=>ipcRenderer.invoke('mcp-configure',settings),
  onMcpRequest:fn=>{const handler=async(_,request)=>{try{ipcRenderer.send('mcp-response',{id:request.id,result:await fn(request.tool,request.args)});}catch(error){ipcRenderer.send('mcp-response',{id:request.id,error:error.message});}};ipcRenderer.on('mcp-request',handler);return ()=>ipcRenderer.removeListener('mcp-request',handler);},
  assets:()=>ipcRenderer.invoke('assets'),
  addLibrary:()=>ipcRenderer.invoke('add-library'),
  assetPreview:id=>ipcRenderer.invoke('asset-preview',id),
  inspectAsset:(id,targetSource)=>ipcRenderer.invoke('inspect-asset',id,targetSource),
  inspectFile:(source,targetSource)=>ipcRenderer.invoke('inspect-file',source,targetSource),
  dsonPreset:(source,sha)=>ipcRenderer.invoke('dson-preset',source,sha),
  dsonTexture:(source,file)=>ipcRenderer.invoke('dson-texture',source,file),
  validateGltf:(data,context)=>ipcRenderer.invoke('validate-gltf',data,context),
  exportGltf:spec=>ipcRenderer.invoke('export-gltf',spec),
  loadAsset:(id,morphs,options)=>ipcRenderer.invoke('load-asset',id,morphs,options),
  applyNative:(source,morphs)=>ipcRenderer.invoke('apply-native',source,morphs),
  save:doc=>ipcRenderer.invoke('save',doc),
  open:()=>ipcRenderer.invoke('open'),
  saveMorphPreset:preset=>ipcRenderer.invoke('save-morph-preset',preset),
  openMorphPreset:()=>ipcRenderer.invoke('open-morph-preset'),
  savePosePreset:preset=>ipcRenderer.invoke('save-pose-preset',preset),
  openPosePreset:()=>ipcRenderer.invoke('open-pose-preset'),
  recent:()=>ipcRenderer.invoke('recent'),
  loadRecent:file=>ipcRenderer.invoke('load-recent',file),
  chooseImport:()=>ipcRenderer.invoke('choose-import'),
  job:spec=>ipcRenderer.invoke('job',spec),
  geometry:(method,request)=>ipcRenderer.invoke('geometry',method,request),
  cancel:()=>ipcRenderer.invoke('cancel'),
  reveal:file=>ipcRenderer.invoke('reveal',file),
  exportOriginal:source=>ipcRenderer.invoke('export-original',source),
  image:file=>ipcRenderer.invoke('image',file),
  chooseEnvironment:()=>ipcRenderer.invoke('choose-environment'),
  environment:file=>ipcRenderer.invoke('environment',file),
  chooseIes:()=>ipcRenderer.invoke('choose-ies'),
  chooseGobo:()=>ipcRenderer.invoke('choose-gobo'),
  chooseCameraTrack:()=>ipcRenderer.invoke('choose-camera-track'),
  lightFile:file=>ipcRenderer.invoke('light-file',file),
  onJob:fn=>{const handler=(_,job)=>fn(job);ipcRenderer.on('job-update',handler);return ()=>ipcRenderer.removeListener('job-update',handler);}
});
